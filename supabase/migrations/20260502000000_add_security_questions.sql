DROP POLICY IF EXISTS "Authenticated users can read security questions" ON public.security_question;
CREATE POLICY "Authenticated users can read security questions"
  ON public.security_question FOR SELECT
  TO authenticated
  USING (is_active = true);

DROP POLICY IF EXISTS "Admins can manage security questions" ON public.security_question;
CREATE POLICY "Admins can manage security questions"
  ON public.security_question FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

