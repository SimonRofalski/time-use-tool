CREATE TABLE IF NOT EXISTS public.security_question (
  security_question_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_text text NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.user_security_question (
  user_security_question_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profiles_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  security_question_id integer NOT NULL REFERENCES public.security_question(security_question_id),
  answer_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT user_security_question_unique_per_question UNIQUE (profiles_id, security_question_id)
);

CREATE TABLE IF NOT EXISTS public.security_question_reset_challenge (
  security_question_reset_challenge_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profiles_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.admin_password_reset_log (
  admin_password_reset_log_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  target_profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  triggered_by_profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_user_security_question_updated_at ON public.user_security_question;
CREATE TRIGGER trg_user_security_question_updated_at
  BEFORE UPDATE ON public.user_security_question
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

