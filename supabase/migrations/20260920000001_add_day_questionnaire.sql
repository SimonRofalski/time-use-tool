-- ─── day_questionnaire: one row per completed day ──────────────────────────
-- All FK columns are NOT NULL: the questionnaire is all-or-nothing once shown
-- (no more conditional branching, since Q7a/Q8b were dropped). Q2-4 reference
-- `activity` directly (the student's most pleasant/unpleasant/stressful
-- *activity* that day, picked from their own primary activities — not a
-- specific time_entry occurrence).

CREATE TABLE IF NOT EXISTS public.day_questionnaire (
  day_questionnaire_id      integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_id                    integer     NOT NULL UNIQUE REFERENCES public.day(day_id) ON DELETE CASCADE,
  diary_fill_timing_id      integer     NOT NULL REFERENCES public.diary_fill_timing(diary_fill_timing_id),
  most_pleasant_activity_id integer     NOT NULL REFERENCES public.activity(activity_id),
  most_unpleasant_activity_id integer   NOT NULL REFERENCES public.activity(activity_id),
  most_stressful_activity_id integer    NOT NULL REFERENCES public.activity(activity_id),
  day_appreciation_id       integer     NOT NULL REFERENCES public.day_appreciation(day_appreciation_id),
  is_unusual_day             boolean    NOT NULL,
  day_type_context_id       integer     NOT NULL REFERENCES public.day_type_context(day_type_context_id),
  trip_type_id               integer    NOT NULL REFERENCES public.trip_type(trip_type_id),
  created_at                 timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at                 timestamptz NOT NULL DEFAULT timezone('utc', now())
);

-- Reuses public.set_updated_at(), already defined in
-- 20260502000000_add_security_questions.sql.
DROP TRIGGER IF EXISTS trg_day_questionnaire_updated_at ON public.day_questionnaire;
CREATE TRIGGER trg_day_questionnaire_updated_at
  BEFORE UPDATE ON public.day_questionnaire
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.day_questionnaire ENABLE ROW LEVEL SECURITY;

-- Users can read/insert/update their own day_questionnaire rows (via the
-- same day.profiles_id = auth.uid() join used for time_entry). Update is
-- permitted (rather than insert-only) so a client-side retry after a
-- network failure can safely upsert on day_id without erroring.
DROP POLICY IF EXISTS "Users can read own day_questionnaire" ON public.day_questionnaire;
CREATE POLICY "Users can read own day_questionnaire"
  ON public.day_questionnaire FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.day
      WHERE day.day_id = day_questionnaire.day_id
        AND day.profiles_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Users can insert own day_questionnaire" ON public.day_questionnaire;
CREATE POLICY "Users can insert own day_questionnaire"
  ON public.day_questionnaire FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.day
      WHERE day.day_id = day_questionnaire.day_id
        AND day.profiles_id = auth.uid()
    )
  );

DROP POLICY IF EXISTS "Users can update own day_questionnaire" ON public.day_questionnaire;
CREATE POLICY "Users can update own day_questionnaire"
  ON public.day_questionnaire FOR UPDATE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.day
      WHERE day.day_id = day_questionnaire.day_id
        AND day.profiles_id = auth.uid()
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.day
      WHERE day.day_id = day_questionnaire.day_id
        AND day.profiles_id = auth.uid()
    )
  );

-- Admins can read all day_questionnaire rows in principle (permissive) —
-- but see the RESTRICTIVE policy below, which mirrors the ethics-review
-- constraint already applied to time_entry in
-- 20260916000000_admin_no_time_entry_access.sql: admins are blocked from
-- reading OTHER users' day_questionnaire answers. Aggregated, de-identified
-- admin statistics must go through app/api/admin/* using the service-role
-- client, exactly like time_entry already does (see lib/admin/statistics.ts).
DROP POLICY IF EXISTS "Admins can read all day_questionnaire" ON public.day_questionnaire;
CREATE POLICY "Admins can read all day_questionnaire"
  ON public.day_questionnaire FOR SELECT
  TO authenticated
  USING (public.is_admin());

DROP POLICY IF EXISTS "Admins cannot read others day_questionnaire" ON public.day_questionnaire;
CREATE POLICY "Admins cannot read others day_questionnaire"
  ON public.day_questionnaire
  AS RESTRICTIVE
  FOR SELECT
  TO authenticated
  USING (
    NOT public.is_admin()
    OR EXISTS (
      SELECT 1 FROM public.day
      WHERE day.day_id = day_questionnaire.day_id
        AND day.profiles_id = auth.uid()
    )
  );
