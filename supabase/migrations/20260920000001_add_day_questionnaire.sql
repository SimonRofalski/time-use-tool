-- ─── Day questionnaire: mandatory end-of-day questions ─────────────────────
-- The moment a day reaches 144/144 filled slots, the app shows a mandatory
-- popup asking 8 questions about the day as a whole (based on the HETUS-style
-- reference diary form, with agreed modifications: Q1 gets a simplified 4th
-- option, Q2-4 pick from that day's own primary activities, Q7a "are you a
-- student or employed" and Q8b "how far did you travel" are dropped, Q7b
-- becomes unconditional). Admin-toggleable per course via
-- course.ask_day_questionnaire (default off — existing courses unaffected).
--
-- All lookup tables mirror the existing convention: {id}, code, name (German),
-- name_en (English).

-- ─── diary_fill_timing (Q1: "When did you fill in the diary?") ─────────────

