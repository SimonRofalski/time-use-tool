-- Safe to run BEFORE the matching app version is deployed: the old app keeps
-- working. Run 20261106000002_finish_access_code_move.sql only AFTER deploy.

-- ─── 1) Users may not change their own role, email or active flag ──────────
-- "Users can update own profile" has no column restriction, so any logged-in
-- user could set profiles.role = 'admin' (or change profiles.email, which the
-- edu-ID linking and the security-question reset look accounts up by) with a
-- plain supabase-js call. The existing trigger already locked the three
-- auth-state columns; this extends it to role, email and is_active.
--
-- Also changed: the check is now "is this a request from a logged-in or
-- anonymous app user?" (current_user = authenticated/anon) instead of "is
-- this not the service role?". Before, manual edits by the team in the
-- Supabase SQL editor (role postgres) were silently reverted too. For that
-- the function must run as the caller (SECURITY INVOKER, the default) —
-- with SECURITY DEFINER, current_user would always be the function owner.

CREATE OR REPLACE FUNCTION public.protect_profiles_auth_fields()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
BEGIN
  IF current_user IN ('authenticated', 'anon') THEN
    NEW.auth_provider        := OLD.auth_provider;
    NEW.must_change_password := OLD.must_change_password;
    NEW.switch_edu_id_sub    := OLD.switch_edu_id_sub;
    NEW.role                 := OLD.role;
    NEW.email                := OLD.email;
    NEW.is_active            := OLD.is_active;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_profiles_auth_fields ON public.profiles;
CREATE TRIGGER trg_protect_profiles_auth_fields
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.protect_profiles_auth_fields();

-- ─── 2) Course access codes: admin-only table ──────────────────────────────
-- course."accessCode" was readable by every logged-in user (the course table
-- is readable for the enrollment list), and the code was only compared in the
-- browser. The codes move to their own table that only admins can read; the
-- enrollment check runs server-side (app/api/courses/enroll). The old column
-- is copied here and dropped in 20261106000002 after the new app is live.

CREATE TABLE IF NOT EXISTS public.course_access_code (
  course_id   integer PRIMARY KEY REFERENCES public.course(course_id) ON DELETE CASCADE,
  access_code text    NOT NULL
);

INSERT INTO public.course_access_code (course_id, access_code)
SELECT course_id, "accessCode"
FROM public.course
WHERE "accessCode" IS NOT NULL AND btrim("accessCode") <> ''
ON CONFLICT (course_id) DO UPDATE SET access_code = EXCLUDED.access_code;

ALTER TABLE public.course_access_code ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admins can read course access codes" ON public.course_access_code;
CREATE POLICY "Admins can read course access codes"
  ON public.course_access_code FOR SELECT
  TO authenticated
  USING (public.is_admin());

DROP POLICY IF EXISTS "Admins can insert course access codes" ON public.course_access_code;
CREATE POLICY "Admins can insert course access codes"
  ON public.course_access_code FOR INSERT
  TO authenticated
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "Admins can update course access codes" ON public.course_access_code;
CREATE POLICY "Admins can update course access codes"
  ON public.course_access_code FOR UPDATE
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "Admins can delete course access codes" ON public.course_access_code;
CREATE POLICY "Admins can delete course access codes"
  ON public.course_access_code FOR DELETE
  TO authenticated
  USING (public.is_admin());

-- Creating a course (course + periods + access code) is several requests from
-- the admin UI; if a later one fails, the UI deletes the half-created course
-- again. That needs a DELETE policy for admins (there is no delete button).
DROP POLICY IF EXISTS "Admins can delete courses" ON public.course;
CREATE POLICY "Admins can delete courses"
  ON public.course FOR DELETE
  TO authenticated
  USING (public.is_admin());

-- ─── 3) Rate limit for the security-question password reset ────────────────
-- Failed answer attempts, keyed by a hash of the entered email (also for
-- emails without an account, so the lock doesn't reveal whether one exists).
-- 5 failures within 15 minutes lock further attempts for that email.
-- Server-only (service role): RLS on, no policies.

CREATE TABLE IF NOT EXISTS public.security_question_reset_attempt (
  attempt_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_hash   text        NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS security_question_reset_attempt_email_time_idx
  ON public.security_question_reset_attempt (email_hash, attempted_at);

ALTER TABLE public.security_question_reset_attempt ENABLE ROW LEVEL SECURITY;
