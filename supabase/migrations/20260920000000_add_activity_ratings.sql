-- ─── time_entry: nullable FKs, same pattern as satisfaction_id ─────────────

ALTER TABLE public.time_entry
  ADD COLUMN IF NOT EXISTS meaningfulness_id integer REFERENCES public.meaningfulness(meaningfulness_id),
  ADD COLUMN IF NOT EXISTS stressfulness_id  integer REFERENCES public.stressfulness(stressfulness_id);

-- ─── course: per-course opt-in toggle ───────────────────────────────────────
-- Combined toggle for both Meaningfulness and Stressfulness together.
-- Mirrors the existing comparison_enabled toggle: boolean, default false,
-- freely editable any time from the admin course-detail view.

ALTER TABLE public.course
  ADD COLUMN IF NOT EXISTS ask_extra_ratings boolean NOT NULL DEFAULT false;
