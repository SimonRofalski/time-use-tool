  ('2', 'Niedrig', 'Low'),
  ('3', 'Mittel', 'Medium'),
  ('4', 'Hoch', 'High'),
  ('5', 'Sehr hoch', 'Very high')
ON CONFLICT (code) DO NOTHING;

ALTER TABLE public.stressfulness ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read stressfulness" ON public.stressfulness;
CREATE POLICY "Authenticated users can read stressfulness"
