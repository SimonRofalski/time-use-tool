-- ─── ICT attention: focused vs. background device use ────────────────────────
-- Follow-up question asked whenever a user answers "yes" to the device question
-- (time_entry.digital_media_used = true): "Was your use of ICT the main focus of
-- your attention, or was it in the background?" Mandatory once shown.
-- Admin-toggleable per course via course.ask_ict_attention (default off —
-- existing courses are unaffected), same pattern as course.ask_extra_ratings.
--
-- Lookup table shape mirrors satisfaction/meaningfulness (id, code, name,
-- name_en) plus a description per language, shown under each answer.

CREATE TABLE IF NOT EXISTS public.ict_attention (
  ict_attention_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             text    NOT NULL UNIQUE,
  name             text    NOT NULL,
  name_en          text    NOT NULL,
  description      text    NOT NULL,
  description_en   text    NOT NULL
);

