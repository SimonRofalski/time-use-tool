ON CONFLICT (code) DO NOTHING;

ALTER TABLE public.ict_attention ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read ict_attention" ON public.ict_attention;
CREATE POLICY "Authenticated users can read ict_attention"
  ON public.ict_attention FOR SELECT
  TO authenticated
  USING (true);

-- ─── time_entry: nullable FK (NULL when no device was used or toggle is off) ─

ALTER TABLE public.time_entry
  ADD COLUMN IF NOT EXISTS ict_attention_id integer REFERENCES public.ict_attention(ict_attention_id);

-- ─── course: per-course opt-in toggle ───────────────────────────────────────

ALTER TABLE public.course
  ADD COLUMN IF NOT EXISTS ask_ict_attention boolean NOT NULL DEFAULT false;
